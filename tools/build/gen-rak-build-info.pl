#!/usr/bin/env perl
# Write an NQP sub that records rak's version, repository URL and HEAD sha1
# into the build config, for the irak banner and `rak --version`. The file is
# only rewritten when its content changes, so an unchanged HEAD does not
# trigger a relink.
#
# The version is `git describe` against the `v*` release tags, without the
# `v` (`0.0.1`, or `0.0.1-5-gabc1234` past the tag), else the RAK_VERSION
# file. A release tarball has no .git: tools/build/rak-dist.sh records the
# URL and HEAD in its RAK_SOURCE file (`URL HEAD`), read here instead.
#
# Usage: gen-rak-build-info.pl OUTFILE
use strict;
use warnings;

my $out = shift or die "usage: $0 OUTFILE\n";

sub git {
    my $r = `git @_ 2>/dev/null`;
    return '' if $?;
    chomp $r;
    return $r;
}

sub first_line {
    my ($file) = @_;
    open my $fh, '<', $file or return '';
    my $line = <$fh> // '';
    close $fh;
    chomp $line;
    return $line;
}

my $url  = '';
my $head = '';
if (-e '.git') {
    $url = git('remote get-url origin');
    $url =~ s{^git\@([^:]+):}{https://$1/};
    $url =~ s{\.git$}{};

    $head = git('rev-parse --short=10 HEAD');
    $head .= '-dirty'
        if $head ne '' && git('status --porcelain --untracked-files=no') ne '';
}
else {
    ($url, $head) = split ' ', first_line('RAK_SOURCE');
    $_ //= '' for $url, $head;
}

my $version = -e '.git' ? git(q{describe --tags --match 'v[0-9]*'}) : '';
$version =~ s/^v//;
($version = first_line('RAK_VERSION')) =~ s/\s+//g if $version eq '';

for ($url, $head, $version) { s/([\\'])/\\$1/g }

my $content = <<"NQP";
# Generated by tools/build/gen-rak-build-info.pl. Do not edit.
sub rak-build-info(\$config) {
    \$config<rak-repo-url> := '$url';
    \$config<rak-head>     := '$head';
    \$config<rak-version>  := '$version';
}
NQP

if (open my $fh, '<', $out) {
    local $/;
    my $old = <$fh>;
    close $fh;
    exit 0 if defined $old && $old eq $content;
}
open my $fh, '>', $out or die "cannot write $out: $!\n";
print $fh $content;
close $fh;
