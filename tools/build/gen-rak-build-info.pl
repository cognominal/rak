#!/usr/bin/env perl
# Write an NQP sub that records the rak repository URL and HEAD sha1 into the
# build config, for the irak banner. The file is only rewritten when its
# content changes, so an unchanged HEAD does not trigger a relink.
#
# Usage: gen-rak-build-info.pl OUTFILE
use strict;
use warnings;

my $out = shift or die "usage: $0 OUTFILE\n";

sub git {
    my $r = `git @_ 2>/dev/null`;
    return '' if $?;
    chomp $r;
    return $r;
}

my $url = git('remote get-url origin');
$url =~ s{^git\@([^:]+):}{https://$1/};
$url =~ s{\.git$}{};

my $head = git('rev-parse --short=10 HEAD');
$head .= '-dirty'
    if $head ne '' && git('status --porcelain --untracked-files=no') ne '';

for ($url, $head) { s/([\\'])/\\$1/g }

my $content = <<"NQP";
# Generated by tools/build/gen-rak-build-info.pl. Do not edit.
sub rak-build-info(\$config) {
    \$config<rak-repo-url> := '$url';
    \$config<rak-head>     := '$head';
}
NQP

if (open my $fh, '<', $out) {
    local $/;
    my $old = <$fh>;
    close $fh;
    exit 0 if defined $old && $old eq $content;
}
open my $fh, '>', $out or die "cannot write $out: $!\n";
print $fh $content;
close $fh;
